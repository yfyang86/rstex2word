"""Generate ``crates/tex2word-ir/src/unicode_norm.rs``: NFC tables taken from
the running CPython's ``unicodedata`` (Unicode 15.0 for CPython 3.12), so the
Rust ``pystr::nfc`` reproduces ``unicodedata.normalize("NFC", s)`` exactly.

Tables:
- DECOMP: canonical (non-compatibility) decompositions, one level deep
  (the runtime recurses); Hangul syllables are handled algorithmically.
- CCC: canonical combining class ranges (non-zero only).
- COMPOSE: primary composites ``(first, second) -> composite``, derived by
  asking CPython itself which canonical pairs recompose under NFC (that folds
  in the composition exclusions and singleton/non-starter rules).

Run with the reference interpreter from the repo root:
    /home/user/py-core/bin/python tools/golden/gen_unicode_norm.py
"""

from __future__ import annotations

import os
import sys
import unicodedata as U

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                   "crates", "tex2word-ir", "src", "unicode_norm.rs")


def main() -> None:
    decomp: list[tuple[int, list[int]]] = []
    compose: list[tuple[int, int, int]] = []
    ccc: list[tuple[int, int, int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        if 0xAC00 <= cp <= 0xD7A3:
            continue  # Hangul: algorithmic
        d = U.decomposition(ch)
        if d and not d.startswith("<"):
            parts = [int(x, 16) for x in d.split()]
            decomp.append((cp, parts))
            if len(parts) == 2 and U.normalize("NFC", "".join(map(chr, parts))) == ch:
                compose.append((parts[0], parts[1], cp))
        c = U.combining(ch)
        if c:
            if ccc and ccc[-1][1] == cp - 1 and ccc[-1][2] == c:
                ccc[-1] = (ccc[-1][0], cp, c)
            else:
                ccc.append((cp, cp, c))
    compose.sort()
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// @generated by tools/golden/gen_unicode_norm.py from CPython "
                 f"{sys.version.split()[0]} (Unicode {U.unidata_version}); do not edit.\n\n")
        fh.write("#[allow(dead_code)] // checked by the tests\n")
        fh.write(f"pub(crate) const UNICODE_VERSION: &str = \"{U.unidata_version}\";\n\n")
        fh.write("/// Canonical decompositions (one level), sorted by code point.\n")
        fh.write("pub(crate) static DECOMP: &[(u32, &[u32])] = &[\n")
        for cp, parts in decomp:
            fh.write(f"    (0x{cp:X}, &[{', '.join(f'0x{p:X}' for p in parts)}]),\n")
        fh.write("];\n\n")
        fh.write("/// Non-zero canonical combining classes: (lo, hi, class).\n")
        fh.write("pub(crate) static CCC: &[(u32, u32, u8)] = &[\n")
        for lo, hi, c in ccc:
            fh.write(f"    (0x{lo:X}, 0x{hi:X}, {c}),\n")
        fh.write("];\n\n")
        fh.write("/// Primary composites: (first, second, composite), sorted.\n")
        fh.write("pub(crate) static COMPOSE: &[(u32, u32, u32)] = &[\n")
        for a, b, c in compose:
            fh.write(f"    (0x{a:X}, 0x{b:X}, 0x{c:X}),\n")
        fh.write("];\n")
    print(f"{len(decomp)} decompositions, {len(ccc)} ccc ranges, {len(compose)} composites",
          file=sys.stderr)


if __name__ == "__main__":
    main()
