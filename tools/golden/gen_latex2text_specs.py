"""Generate ``crates/tex2word-latexwalker/src/latex2text_specs.rs`` from
pylatexenc's ``latex2text.get_default_latex_context_db()``.

String replacements are copied verbatim; the replacement callables are
identified by their source location and emitted as ``Fn::...`` variants that
``latex2text.rs`` implements by hand (closure parameters such as a math style
or an accent's combining character are carried in the variant).

Run with the reference interpreter from the repo root:
    /home/user/py-core/bin/python tools/golden/gen_latex2text_specs.py
"""

from __future__ import annotations

import os
import sys

import pylatexenc
from pylatexenc.latex2text import get_default_latex_context_db

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                   "crates", "tex2word-latexwalker", "src", "latex2text_specs.rs")


def rs(s: str) -> str:
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif ord(c) < 0x20 or ord(c) == 0x7F or (0x80 <= ord(c) < 0xA0) \
                or c in " ​             　" \
                or 0x300 <= ord(c) < 0x370:
            out.append(f"\\u{{{ord(c):x}}}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


# (file, first line) of each replacement callable -> Rust variant (Python 2.11)
NAMED = {
    ("__init__.py", "fmt_equation_environment"): "Fn::EquationEnv",
    ("__init__.py", "fmt_input_macro"): "Fn::InputMacro",
    ("__init__.py", "fmt_matrix_environment_node"): "Fn::MatrixEnv",
    ("_defaultspecs.py", "_format_uebung"): "Fn::Uebung",
}
LAMBDA_BY_SPEC = {
    "title": "Fn::Title", "author": "Fn::Author", "date": "Fn::Date",
    "maketitle": "Fn::Maketitle", "item": "Fn::Item", "href": "Fn::Href",
    "part": "Fn::Part", "chapter": "Fn::Chapter", "section": "Fn::Section",
    "subsection": "Fn::Subsection", "subsubsection": "Fn::Subsubsection",
    "paragraph": "Fn::Paragraph", "subparagraph": "Fn::Subparagraph",
    "texorpdfstring": "Fn::Texorpdfstring", "%": "Fn::Percent",
}


def fn_variant(name: str, r) -> str:
    code = r.__code__
    fname = code.co_filename.split("/")[-1]
    if (fname, code.co_name) in NAMED:
        return NAMED[(fname, code.co_name)]
    if fname == "_defaultspecs.py" and code.co_name == "formatter":
        return f"Fn::MathStyle({rs(r.__defaults__[0])})"
    if fname == "__init__.py" and code.co_name == "<lambda>" and code.co_varnames[:3] == ("n", "l2tobj", "pht"):
        return f"Fn::Placeholder({rs(r.__defaults__[0])})"
    if fname == "_defaultspecs.py" and code.co_name == "<lambda>" and "c" in code.co_varnames \
            and code.co_varnames[:3] == ("x", "l2tobj", "c"):
        return f"Fn::Accent({rs(r.__defaults__[0])})"
    if fname == "_defaultspecs.py" and code.co_name == "<lambda>" and name in LAMBDA_BY_SPEC:
        return LAMBDA_BY_SPEC[name]
    raise SystemExit(f"unmapped callable for {name!r}: {fname}:{code.co_firstlineno} {code.co_name}")


def spec(name: str, s, has_discard: bool) -> str:
    r = s.simplify_repl
    if name == "today" and isinstance(r, str):
        # evaluated with datetime.now() at import time in pylatexenc
        return f"({rs(name)}, TextSpec {{ repl: Repl::Fn(Fn::Today), discard: Some({str(s.discard).lower()}) }})"
    if r is None:
        repl = "Repl::None"
    elif callable(r):
        repl = f"Repl::Fn({fn_variant(name, r)})"
    else:
        repl = f"Repl::Str({rs(r)})"
    discard = f"Some({str(s.discard).lower()})" if has_discard else "None"
    return f"({rs(name)}, TextSpec {{ repl: {repl}, discard: {discard} }})"


def main() -> None:
    assert pylatexenc.__version__ == "2.11", pylatexenc.__version__
    db = get_default_latex_context_db()
    lines = [
        f"// @generated by tools/golden/gen_latex2text_specs.py from pylatexenc "
        f"{pylatexenc.__version__}; do not edit.",
        "",
        "use crate::latex2text::{Fn, Repl, TextSpec};",
        "",
        "/// `latex2text.get_default_latex_context_db()`: (category, macros,",
        "/// environments, specials), in lookup order.",
        "#[allow(clippy::type_complexity)]",
        "pub(crate) static L2T_CATEGORIES: &[(&str, &[(&str, TextSpec)], &[(&str, TextSpec)], &[(&str, TextSpec)])] = &[",
    ]
    for cat in db.categories():
        cs = db.d[cat]
        lines.append(f"    ({rs(cat)}, &[")
        for name, s in cs["macros"].items():
            lines.append(f"        {spec(name, s, True)},")
        lines.append("    ], &[")
        for name, s in cs["environments"].items():
            lines.append(f"        {spec(name, s, True)},")
        lines.append("    ], &[")
        for name, s in cs["specials"].items():
            lines.append(f"        {spec(name, s, hasattr(s, 'discard'))},")
        lines.append("    ]),")
    lines.append("];")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    n = sum(len(db.d[c][k]) for c in db.categories() for k in ("macros", "environments", "specials"))
    print(f"{n} specs in {len(db.categories())} categories -> {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
