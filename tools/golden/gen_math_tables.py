"""Generate ``crates/tex2word-math/src/symbols.rs`` from the reference's
``mathml/symbols.py`` (the tables are full of combining marks and special
spaces, so they are copied mechanically rather than retyped).

    /home/user/py-core/bin/python tools/golden/gen_math_tables.py
"""

import os
import sys

sys.path.insert(0, "/home/user/yfyang86/tex2word/src")
from tex2word.mathml import symbols as S  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                   "crates", "tex2word-math", "src", "symbols.rs")


def rs(s: str) -> str:
    out = []
    for c in s:
        if c in '\\"':
            out.append("\\" + c)
        elif c.isascii() and c.isprintable():
            out.append(c)
        elif c.isprintable() and not c.isspace() and ord(c) >= 0x370 and not (0x2000 <= ord(c) <= 0x20FF):
            out.append(c)
        else:
            out.append(f"\\u{{{ord(c):x}}}")
    return '"' + "".join(out) + '"'


def table(name, doc, d):
    lines = [f"/// {doc}", f"pub static {name}: &[(&str, &str)] = &["]
    lines += [f"    ({rs(k)}, {rs(v)})," for k, v in d.items()]
    lines.append("];")
    return "\n".join(lines)


def main():
    parts = [
        "// @generated by tools/golden/gen_math_tables.py from the reference's mathml/symbols.py; do not edit.",
        "//! LaTeX-math command tables: symbols, operators, accents, delimiters.",
        "",
        table("SYMBOLS", "Greek + symbols rendered as a single Unicode glyph.", S.SYMBOLS),
        table("NARY", "n-ary / big operators (rendered with limits via OMML m:nary).", S.NARY),
        table("ACCENTS", "Accents: command -> accent character used by OMML m:acc.", S.ACCENTS),
        "/// Upright multi-letter function names.",
        "pub static FUNCTIONS: &[&str] = &[" + ", ".join(rs(f) for f in sorted(S.FUNCTIONS)) + "];",
        table("DELIMITERS", "Delimiter commands -> the literal delimiter character.", S.DELIMITERS),
        table("MATHBB", "Blackboard-bold (\\mathbb) letters -> Unicode double-struck.", S.MATHBB),
        table("SPACING", "Spacing commands that produce (roughly) nothing / thin spaces.", S.SPACING),
        "",
        "/// Look up a key in a table.",
        "pub fn get(table: &'static [(&'static str, &'static str)], key: &str) -> Option<&'static str> {",
        "    table.iter().find(|(k, _)| *k == key).map(|(_, v)| *v)",
        "}",
        "",
        "/// Membership in [`FUNCTIONS`].",
        "pub fn is_function(name: &str) -> bool {",
        "    FUNCTIONS.contains(&name)",
        "}",
    ]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n\n".join(parts) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
