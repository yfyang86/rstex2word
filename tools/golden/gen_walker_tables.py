"""Generate Rust tables for tex2word-latexwalker from the Python reference.

    python tools/golden/gen_walker_tables.py   # run with the reference venv

Writes two files under ``crates/tex2word-latexwalker/src/``:

* ``unicode_tables.rs`` -- Python's ``str.isalpha()``, ``str.isalnum()`` (the
  regex ``\\w`` class minus ``_``) and ``str.isspace()`` as code-point range
  tables, taken from the running interpreter's Unicode database. pylatexenc
  tokenises with these predicates, and they differ from Rust's ``char``
  methods at the edges (e.g. ``Nl`` letters, ``Other_Alphabetic`` marks).
* ``default_specs.rs`` -- pylatexenc's ``get_default_latex_context_db()``:
  every category, macro, environment and specials spec with its argument
  parser, in the database's own order.

Regenerate whenever the reference's Python or pylatexenc version changes.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

import pylatexenc
from pylatexenc.latexwalker import get_default_latex_context_db

OUT = Path(__file__).resolve().parents[2] / "crates" / "tex2word-latexwalker" / "src"

HEADER = (
    "// @generated by tools/golden/gen_walker_tables.py from Python {py} "
    "(Unicode {uni}), pylatexenc {ple}. Do not edit.\n"
).format(
    py=".".join(map(str, sys.version_info[:3])),
    uni=unicodedata.unidata_version,
    ple=pylatexenc.__version__,
)


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(sys.maxunicode + 2):
        hit = cp <= sys.maxunicode and pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit_ranges(name: str, doc: str, rs: list[tuple[int, int]]) -> str:
    body = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in rs)
    return f"/// {doc}\npub(crate) static {name}: &[(u32, u32)] = &[\n{body}\n];\n"


def gen_unicode() -> None:
    text = HEADER + "\n"
    text += emit_ranges("ALPHA", "Python `str.isalpha()` code-point ranges.",
                        ranges(str.isalpha)) + "\n"
    text += emit_ranges("ALNUM", "Python `str.isalnum()` code-point ranges (regex `\\w` minus `_`).",
                        ranges(str.isalnum)) + "\n"
    text += emit_ranges("SPACE", "Python `str.isspace()` code-point ranges.",
                        ranges(str.isspace))
    (OUT / "unicode_tables.rs").write_text(text)


def rs_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parser_expr(ap) -> str:
    if ap is None:
        return "None"
    kind = type(ap).__name__
    if kind == "VerbatimArgsParser":
        arg = {"verb-macro": "VerbMacro", "verbatim-environment": "VerbatimEnvironment"}[
            ap.verbatim_arg_type]
        return f"Some(ArgsParser::Verbatim(VerbatimKind::{arg}))"
    if kind != "MacroStandardArgsParser":
        raise TypeError(f"unsupported args parser {kind}")
    if ap.args_math_mode is None:
        amm = "None"
    else:
        items = ", ".join("None" if x is None else f"Some({str(bool(x)).lower()})"
                          for x in ap.args_math_mode)
        amm = f"Some(&[{items}])"
    return (f"Some(ArgsParser::standard_full({rs_str(ap.argspec)}, "
            f"{str(bool(ap.optional_arg_no_space)).lower()}, {amm}))")


def gen_specs() -> None:
    db = get_default_latex_context_db()
    lines = [HEADER, "use crate::spec::{ArgsParser, VerbatimKind};", "",
             "/// One default context category: `(name, macros, environments, specials)`.",
             "pub(crate) type DefaultCategory = (",
             "    &'static str,",
             "    &'static [(&'static str, Option<ArgsParser>)],",
             "    &'static [(&'static str, Option<ArgsParser>, bool)],",
             "    &'static [&'static str],",
             ");", "",
             "/// pylatexenc's `get_default_latex_context_db()`, in database order.",
             "pub(crate) static DEFAULT_CATEGORIES: &[DefaultCategory] = &["]
    for cat in db.category_list:
        d = db.d[cat]
        lines.append(f"    (\n        {rs_str(cat)},\n        &[")
        for name, spec in d["macros"].items():
            lines.append(f"            ({rs_str(name)}, {parser_expr(spec.args_parser)}),")
        lines.append("        ],\n        &[")
        for name, spec in d["environments"].items():
            lines.append(f"            ({rs_str(name)}, {parser_expr(spec.args_parser)}, "
                         f"{str(bool(spec.is_math_mode)).lower()}),")
        lines.append("        ],\n        &[")
        for chars, spec in d["specials"].items():
            if spec.args_parser is not None:
                raise TypeError("specials with argument parsers are not supported")
            lines.append(f"            {rs_str(chars)},")
        lines.append("        ],\n    ),")
    lines.append("];\n")
    (OUT / "default_specs.rs").write_text("\n".join(lines))


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    gen_unicode()
    gen_specs()
    print(f"wrote {OUT / 'unicode_tables.rs'} and {OUT / 'default_specs.rs'}")
