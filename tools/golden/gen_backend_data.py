"""Generate ``crates/tex2word-backend/src/data.rs``: the verbatim XML/text
constants of the reference backend (numbering.xml, OPC package boilerplate,
running-head templates), copied mechanically so they stay byte-identical.

    /home/user/py-core/bin/python tools/golden/gen_backend_data.py
"""

import os
import sys

sys.path.insert(0, "/home/user/yfyang86/tex2word/src")
from tex2word.backend import numbering, package, runninghead  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                   "crates", "tex2word-backend", "src", "data.rs")


def raw(s: str) -> str:
    hashes = "#"
    while f'"{hashes}' in s:
        hashes += "#"
    return f'r{hashes}"{s}"{hashes}'


CONSTS = [
    ("NUMBERING_XML", numbering._NUMBERING_XML),
    ("MANIFEST_PART", package.MANIFEST_PART),
    ("MANIFEST_REL_TYPE", package.MANIFEST_REL_TYPE),
    ("CONTENT_TYPES_HEAD", package._CONTENT_TYPES_HEAD),
    ("MANIFEST_OVERRIDE", package._MANIFEST_OVERRIDE),
    ("FOOTNOTES_OVERRIDE", package._FOOTNOTES_OVERRIDE),
    ("ENDNOTES_OVERRIDE", package._ENDNOTES_OVERRIDE),
    ("THEME_OVERRIDE", package._THEME_OVERRIDE),
    ("COMMENTS_OVERRIDE", package._COMMENTS_OVERRIDE),
    ("CONTENT_TYPES_TAIL", package._CONTENT_TYPES_TAIL),
    ("ROOT_RELS", package._ROOT_RELS),
    ("SETTINGS", package._SETTINGS),
    ("CORE_PROPS", package._CORE_PROPS),
    ("HEADER_TMPL", runninghead._HEADER_TMPL),
    ("FOOTER_XML", runninghead._FOOTER_XML),
]


def main():
    out = ["// @generated by tools/golden/gen_backend_data.py from the reference backend; do not edit.",
           "//! Verbatim XML/text constants of the reference backend.", ""]
    for name, value in CONSTS:
        assert isinstance(value, str), name
        out.append(f"pub const {name}: &str = {raw(value)};")
        out.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
